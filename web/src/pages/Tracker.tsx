import React, { useState, useEffect } from 'react';
import { useLanguage } from '../context/LanguageContext';
import { api } from '../api';
import { Application } from '../types';
import { LoadingState, EmptyState, ErrorState } from '../components/common/UIStates';
import {
  FileText,
  Download,
  Calendar,
  CheckCircle2,
  Clock,
  AlertCircle,
  MapPin,
  ExternalLink,
  ChevronRight,
  ArrowRight,
  Sparkles,
  Edit2,
  Building,
  Check
} from 'lucide-react';

const STAGES = ['DRAFT', 'READY_TO_SUBMIT', 'SUBMITTED', 'APPROVED'];

export const Tracker: React.FC = () => {
  const { t, language } = useLanguage();

  const [applications, setApplications] = useState<Application[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Selected application for detail modal
  const [selectedApp, setSelectedApp] = useState<Application | null>(null);
  const [notesText, setNotesText] = useState('');
  const [isEditingNotes, setIsEditingNotes] = useState(false);

  useEffect(() => {
    loadApps();
  }, []);

  const loadApps = async () => {
    try {
      setLoading(true);
      setError(null);
      const data = await api.getApplications();
      setApplications(data);
    } catch (err: any) {
      setError(err?.message || 'Failed to load applications.');
    } finally {
      setLoading(false);
    }
  };

  const handleDownloadPdf = (app: Application) => {
    // Generate dummy printable text file or simulated PDF download
    const blob = new Blob(
      [
        `GOVERNMENT OF INDIA - SCHEME APPLICATION FORM\nScheme: ${app.scheme_name}\nApplication Ref: ${app.id}\nStatus: ${app.status}\nDocuments Attached: ${app.documents_ready.join(', ')}\nNext Action: ${app.next_action}\nGenerated By: YojanaAgent Autonomous AI Assistant\nDate: ${new Date().toLocaleDateString()}`
      ],
      { type: 'text/plain' }
    );
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Application_${app.scheme_id}_Prefilled.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadIcs = (app: Application) => {
    // Standard .ics calendar invite
    const icsData = `BEGIN:VCALENDAR\nVERSION:2.0\nPRODID:-//YojanaAgent//Scheme Calendar//EN\nBEGIN:VEVENT\nSUMMARY:Deadline for ${app.scheme_name}\nDESCRIPTION:${app.next_action}\nDTSTART:20260331T090000Z\nDTEND:20260331T100000Z\nSTATUS:CONFIRMED\nEND:VEVENT\nEND:VCALENDAR`;
    const blob = new Blob([icsData], { type: 'text/calendar;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${app.scheme_id}_reminder.ics`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleOpenDetail = (app: Application) => {
    setSelectedApp(app);
    setNotesText(app.notes || '');
    setIsEditingNotes(false);
  };

  const handleSaveNotes = async () => {
    if (!selectedApp) return;
    await api.updateApplication(selectedApp.id, selectedApp.status, notesText);
    setSelectedApp({ ...selectedApp, notes: notesText });
    setIsEditingNotes(false);
    loadApps();
  };

  if (loading) {
    return <LoadingState message={language === 'hi' ? 'आवेदन प्रगति विवरण लोड हो रहा है...' : 'Synchronizing application lifecycles from nodal registries...'} />;
  }

  if (error) {
    return <ErrorState message={error} onRetry={loadApps} />;
  }

  return (
    <div className="space-y-6">
      {/* Top Header */}
      <div className="bg-white rounded-2xl p-5 border border-slate-200/80 shadow-xs flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-slate-900">
            {t('tracker.title')}
          </h1>
          <p className="text-sm text-slate-500 mt-0.5">
            {language === 'hi'
              ? 'आपके तैयार आवेदन पत्र, सत्यापन स्थिति और नजदीकी सीएससी केंद्र'
              : 'End-to-end lifecycle monitoring with pre-filled forms and CSC assistance'}
          </p>
        </div>

        <span className="px-3.5 py-1.5 rounded-full text-xs font-bold bg-green-50 text-gov-green border border-green-200">
          {applications.length} {language === 'hi' ? 'सक्रिय आवेदन' : 'Active Applications'}
        </span>
      </div>

      {/* Applications List */}
      <div className="space-y-4">
        {applications.length === 0 ? (
          <EmptyState
            title={language === 'hi' ? 'कोई आवेदन सक्रिय नहीं है' : 'No active applications'}
            description={language === 'hi' ? 'पात्र योजनाएं खोजें और एक क्लिक में आवेदन तैयार करें।' : 'Go to Schemes tab and click "Prepare application" to create prefilled packages.'}
          />
        ) : (
          applications.map((app) => {
            const currentStageIndex = STAGES.indexOf(app.status);
            const totalDocs = app.documents_ready.length + app.documents_missing.length;
            const docPercent = totalDocs > 0 ? Math.round((app.documents_ready.length / totalDocs) * 100) : 100;

            return (
              <div
                key={app.id}
                className="bg-white rounded-2xl border border-slate-200/90 shadow-xs hover:shadow-md transition p-5 space-y-4"
              >
                {/* Top Row: Scheme Title & Current Status */}
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div>
                    <h2
                      onClick={() => handleOpenDetail(app)}
                      className="text-base sm:text-lg font-bold text-slate-900 hover:text-saffron-600 transition cursor-pointer"
                    >
                      {app.scheme_name}
                    </h2>
                    <span className="text-xs text-slate-400 font-mono mt-0.5 block">
                      Ref: {app.id} • Updated: {app.updated_at}
                    </span>
                  </div>

                  <span
                    className={`px-3 py-1 rounded-full text-xs font-bold ${
                      app.status === 'APPROVED'
                        ? 'bg-green-100 text-gov-green'
                        : app.status === 'READY_TO_SUBMIT'
                        ? 'bg-orange-100 text-saffron-800 border border-saffron-200'
                        : app.status === 'REJECTED'
                        ? 'bg-red-100 text-red-700'
                        : 'bg-slate-100 text-slate-700'
                    }`}
                  >
                    {app.status.replace(/_/g, ' ')}
                  </span>
                </div>

                {/* Status Stepper */}
                <div className="py-2">
                  <div className="grid grid-cols-4 gap-2 text-center text-xs">
                    {STAGES.map((stage, idx) => {
                      const isComplete = idx <= currentStageIndex;
                      const isCurrent = idx === currentStageIndex;

                      return (
                        <div key={stage} className="flex flex-col items-center">
                          <div
                            className={`w-7 h-7 rounded-full flex items-center justify-center font-bold text-xs transition mb-1 ${
                              isComplete
                                ? 'bg-saffron-500 text-white shadow-xs'
                                : 'bg-slate-100 text-slate-400'
                            }`}
                          >
                            {isComplete ? <Check className="w-4 h-4" /> : idx + 1}
                          </div>
                          <span
                            className={`text-[10px] sm:text-xs leading-tight ${
                              isCurrent ? 'font-bold text-saffron-600' : 'text-slate-500 font-medium'
                            }`}
                          >
                            {stage === 'DRAFT'
                              ? (language === 'hi' ? 'ड्राफ्ट' : 'Draft')
                              : stage === 'READY_TO_SUBMIT'
                              ? (language === 'hi' ? 'जमा करने हेतु तैयार' : 'Ready')
                              : stage === 'SUBMITTED'
                              ? (language === 'hi' ? 'जमा हुआ' : 'Submitted')
                              : (language === 'hi' ? 'स्वीकृत' : 'Approved')}
                          </span>
                        </div>
                      );
                    })}
                  </div>
                </div>

                {/* Documents Ready vs Missing Progress Bar */}
                <div className="space-y-1.5 p-3 bg-slate-50 rounded-xl border border-slate-100">
                  <div className="flex items-center justify-between text-xs">
                    <span className="font-semibold text-slate-700">
                      {language === 'hi' ? 'आवश्यक दस्तावेज़ संलग्नता:' : 'Documents Readiness:'}
                    </span>
                    <span className="font-bold text-slate-900">
                      {app.documents_ready.length} of {totalDocs} ({docPercent}%)
                    </span>
                  </div>

                  <div className="w-full bg-slate-200 h-2 rounded-full overflow-hidden">
                    <div
                      className="bg-gov-green h-full rounded-full transition-all duration-500"
                      style={{ width: `${docPercent}%` }}
                    />
                  </div>

                  {app.documents_missing.length > 0 && (
                    <div className="text-[11px] text-amber-700 font-medium mt-1">
                      {language === 'hi' ? 'शेष दस्तावेज़:' : 'Missing:'} {app.documents_missing.join(', ')}
                    </div>
                  )}
                </div>

                {/* Next Action in One Sentence */}
                <div className="p-3 bg-orange-50/60 rounded-xl border border-saffron-200 text-xs sm:text-sm text-slate-800 flex items-start gap-2">
                  <ArrowRight className="w-4 h-4 text-saffron-600 shrink-0 mt-0.5" />
                  <div>
                    <span className="font-bold text-slate-900">
                      {language === 'hi' ? 'अगला कदम:' : 'Next Action:'}
                    </span>{' '}
                    <span>{app.next_action}</span>
                  </div>
                </div>

                {/* Action Buttons Row */}
                <div className="pt-2 border-t border-slate-100 flex flex-wrap items-center justify-between gap-3">
                  <div className="flex items-center gap-2">
                    {/* PDF Download */}
                    <button
                      type="button"
                      onClick={() => handleDownloadPdf(app)}
                      className="min-h-[42px] px-3.5 py-1.5 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center gap-1.5 transition"
                    >
                      <Download className="w-4 h-4 text-saffron-600" />
                      <span>{t('tracker.prefilled_pdf')}</span>
                    </button>

                    {/* .ics Calendar */}
                    <button
                      type="button"
                      onClick={() => handleDownloadIcs(app)}
                      className="min-h-[42px] px-3.5 py-1.5 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center gap-1.5 transition"
                    >
                      <Calendar className="w-4 h-4 text-slate-500" />
                      <span>{t('tracker.calendar_ics')}</span>
                    </button>
                  </div>

                  <button
                    type="button"
                    onClick={() => handleOpenDetail(app)}
                    className="text-xs font-bold text-saffron-600 hover:text-saffron-700 flex items-center gap-1 py-1.5 px-2 rounded-lg hover:bg-orange-50 transition"
                  >
                    <span>{language === 'hi' ? 'विवरण व सीएससी सहायता' : 'Timeline & CSC Help'}</span>
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Detail Modal with Notes, History Timeline & CSC Guidance */}
      {selectedApp && (
        <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4 z-50 animate-fade-in">
          <div className="bg-white rounded-2xl max-w-xl w-full max-h-[90vh] overflow-y-auto p-6 shadow-2xl border border-slate-200 space-y-5">
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <div>
                <h3 className="font-bold text-slate-900 text-lg">
                  {selectedApp.scheme_name}
                </h3>
                <span className="text-xs text-slate-400 font-mono">
                  ID: {selectedApp.id}
                </span>
              </div>
              <button
                type="button"
                onClick={() => setSelectedApp(null)}
                className="text-slate-400 hover:text-slate-700 p-1"
              >
                ✕
              </button>
            </div>

            {/* Notes Field */}
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <span className="text-xs font-bold text-slate-700 uppercase tracking-wider">
                  {language === 'hi' ? 'निजी नोट्स व टिप्पणी:' : 'Personal Application Notes:'}
                </span>
                {!isEditingNotes && (
                  <button
                    type="button"
                    onClick={() => setIsEditingNotes(true)}
                    className="text-xs text-saffron-600 font-semibold flex items-center gap-1"
                  >
                    <Edit2 className="w-3.5 h-3.5" />
                    <span>{language === 'hi' ? 'संपादित करें' : 'Edit'}</span>
                  </button>
                )}
              </div>

              {isEditingNotes ? (
                <div className="space-y-2">
                  <textarea
                    rows={3}
                    value={notesText}
                    onChange={(e) => setNotesText(e.target.value)}
                    className="w-full p-2.5 text-xs sm:text-sm border border-saffron-500 rounded-xl focus:outline-none"
                  />
                  <div className="flex justify-end gap-2">
                    <button
                      type="button"
                      onClick={() => setIsEditingNotes(false)}
                      className="px-3 py-1.5 text-xs text-slate-600"
                    >
                      {language === 'hi' ? 'रद्द करें' : 'Cancel'}
                    </button>
                    <button
                      type="button"
                      onClick={handleSaveNotes}
                      className="px-4 py-1.5 bg-saffron-500 text-white rounded-lg text-xs font-bold"
                    >
                      {language === 'hi' ? 'सहेजें' : 'Save'}
                    </button>
                  </div>
                </div>
              ) : (
                <div className="p-3 bg-slate-50 rounded-xl border border-slate-200 text-xs sm:text-sm text-slate-700">
                  {selectedApp.notes || (language === 'hi' ? 'कोई विशेष टिप्पणी नहीं है।' : 'No notes added yet.')}
                </div>
              )}
            </div>

            {/* History Timeline */}
            <div className="space-y-3">
              <span className="text-xs font-bold text-slate-700 uppercase tracking-wider block">
                {language === 'hi' ? 'आवेदन का इतिहास' : 'Lifecycle Stage History'}
              </span>

              <div className="relative pl-6 space-y-3 text-xs">
                <div className="absolute left-2.5 top-2 bottom-2 w-0.5 bg-slate-200" />
                {selectedApp.history?.map((h, i) => (
                  <div key={i} className="relative">
                    <div className="absolute -left-6 top-1 w-3 h-3 rounded-full bg-saffron-500" />
                    <span className="font-bold text-slate-900 block">{h.stage}</span>
                    <span className="text-slate-500 text-[11px]">{h.timestamp}</span>
                    <p className="text-slate-600 mt-0.5">{h.note}</p>
                  </div>
                ))}
              </div>
            </div>

            {/* CSC Guidance & Map Link */}
            <div className="p-4 bg-orange-50/70 border border-saffron-200 rounded-xl space-y-2">
              <div className="flex items-center gap-2 font-bold text-slate-900 text-sm">
                <Building className="w-4 h-4 text-saffron-600" />
                <span>{language === 'hi' ? 'निकटतम सीएससी सेवा केंद्र मार्गदर्शन' : 'Common Service Centre (CSC) Guidance'}</span>
              </div>
              <p className="text-xs text-slate-600 leading-relaxed">
                {language === 'hi'
                  ? 'यदि ऑनलाइन आवेदन में बायोमेट्रिक या फिंगरप्रिंट की आवश्यकता हो, तो अपना आधार कार्ड और यह प्री-फिल्ड फॉर्म लेकर नजदीकी सीएससी केंद्र जाएं।'
                  : 'If biometric authentication is mandated, take your Aadhaar card and the pre-filled PDF to the verified CSC operator.'}
              </p>

              <div className="pt-2 flex items-center justify-between text-xs">
                <div className="flex items-center gap-1.5 text-slate-700 font-semibold">
                  <MapPin className="w-4 h-4 text-saffron-600" />
                  <span>CSC Rohtak Central, Bus Stand Road</span>
                </div>
                <a
                  href="https://maps.google.com"
                  target="_blank"
                  rel="noopener noreferrer"
                  className="font-bold text-saffron-600 hover:underline flex items-center gap-1"
                >
                  <span>Google Maps</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              </div>
            </div>

            <button
              type="button"
              onClick={() => setSelectedApp(null)}
              className="w-full py-2.5 bg-slate-100 hover:bg-slate-200 text-slate-800 font-bold rounded-xl text-sm transition"
            >
              {language === 'hi' ? 'बंद करें' : 'Close'}
            </button>
          </div>
        </div>
      )}
    </div>
  );
};
